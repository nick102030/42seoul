#include <unistd.h>

void	ft_print_comb(void)
{
	char	ch[3];

	ch[0] = '0';
	while (ch[0] <= '7')
	{
		ch[1] = ch[0] + 1;
		while (ch[1] <= '8')
		{
			ch[2] = ch[1] + 1;
			while (ch[2] <= '9')
			{
				write (1, &ch, 3);
				if (ch[0] != '7')
				{
					write (1, ", ", 2);
				}
				ch[2]++;
			}
			ch[1]++;
		}
		ch[0]++;
	}
}
