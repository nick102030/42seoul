int	ft_sqrt(int nb)
{
	long long	tmp;

	if (nb <= 0)
		return (0);
	tmp = 1;
	while (tmp * tmp < nb)
		tmp++;
	if (tmp * tmp == nb)
		return (tmp);
	return (0);
}
